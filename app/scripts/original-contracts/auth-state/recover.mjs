// Static adaptation of one original client predicate factory; no bundle evaluation.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parse } from '@babel/parser';
import { generate } from '@babel/generator';
import { openCorpus, exactlyOne, findNodes, member, literal, sha256 } from '../source.mjs';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
export const source = 'evidence/web/objects/9bafadffbe6dc98b.js';
const factorySha = 'daab8eaf8a9c658f957e38a5748b14b24972bd7ba4d53ca758d83c48af094545';
const consumerSha = '4d12898c1c6cd0bc4e8518537175ecf57e5edf14a6723c4c15f8aad0bf97a400';
const kernelPath = 'packages/frontend/src/original-contracts/auth-state/kernel.mjs';
const receiptPath = 'research/original-auth-state-20261028/PROVENANCE.json';
const id = (name) => ({ type: 'Identifier', name });
const code = (node) => generate(node, { comments: false }).code;

export function assertOriginalAdaptation(actual, expected) {
  const metadata = ['start', 'end', 'loc', 'extra', 'leadingComments', 'trailingComments', 'innerComments', 'comments'];
  const ast = (text) => JSON.parse(JSON.stringify(parse(text, { sourceType: 'module' }).program,
    (key, value) => metadata.includes(key) ? undefined : value));
  assert.deepEqual(ast(actual), ast(expected), 'auth-state kernel differs from authenticated original AST');
  assert.equal(sha256(actual), sha256(expected), 'auth-state canonical generated bytes changed');
}

export async function recover({ check = true } = {}) {
  const corpus = await openCorpus(appRoot);
  const factory = await corpus.factory(553301, { source });
  assert.equal(factory.provenance.sha256, factorySha);
  const [imports, exports] = factory.node.body.body;
  assert.equal(factory.node.body.body.length, 2);
  assert.equal(imports.type, 'VariableDeclaration');
  assert.equal(imports.declarations.length, 1);
  const dependency = imports.declarations[0];
  assert.ok(member(dependency.init?.callee, factory.runtime, 'i'));
  assert.equal(dependency.init.arguments.length, 1);
  assert.equal(literal(dependency.init.arguments[0]), 683023);
  assert.equal(exports.type, 'ExpressionStatement');
  assert.ok(member(exports.expression.callee, factory.runtime, 's'));
  const entries = exports.expression.arguments[0];
  assert.equal(entries.type, 'ArrayExpression');
  assert.equal(entries.elements.length, 9);
  const props = [];
  const witnesses = [factory.witness(imports, 'decoder import683023')];
  for (const [offset, name] of [[0, 'U'], [3, 'K'], [6, 'O']]) {
    assert.equal(literal(entries.elements[offset]), name);
    assert.equal(literal(entries.elements[offset + 1]), 0);
    const expression = entries.elements[offset + 2];
    assert.equal(expression.type, 'ArrowFunctionExpression');
    props.push({ type: 'ObjectProperty', key: id(name), value: expression, computed: false, shorthand: false });
    witnesses.push(factory.witness(expression, `export ${name}`));
  }
  const kernel = { type: 'ExportNamedDeclaration', declaration: { type: 'FunctionDeclaration',
    id: id('createAuthStateKernel'), params: [dependency.id, id('Date')], generator: false, async: false,
    body: { type: 'BlockStatement', body: [{ type: 'ReturnStatement', argument: { type: 'ObjectExpression', properties: props } }] } },
    specifiers: [], source: null };
  const output = `// Source-adapted original553301; SHA256 ${factorySha}.\n` +
    '// Decoder and clock are injected; these are browser UI predicates, not authorization.\n' + code(kernel) + '\n';
  if (check) assertOriginalAdaptation(await readFile(path.join(appRoot, kernelPath), 'utf8'), output);
  else await writeFile(path.join(appRoot, kernelPath), output);

  const consumer = await corpus.factory(589428, { source });
  assert.equal(consumer.provenance.sha256, consumerSha);
  const binding = exactlyOne(findNodes(consumer.node, (node) => node.type === 'VariableDeclarator' &&
    member(node.init?.callee, consumer.runtime, 'i') && node.init.arguments[0]?.value === 553301), 'actual predicate import');
  const calls = findNodes(consumer.node, (node) => node.type === 'CallExpression' &&
    node.callee.type === 'SequenceExpression' &&
    member(node.callee.expressions.at(-1), binding.id.name, 'K'));
  assert.equal(calls.length, 1);
  const call = calls[0];
  assert.equal(call.arguments.length, 1);
  const fields = call.arguments[0].properties;
  assert.deepEqual(fields.map((node) => node.key.name), ['decodedJwt', 'privyAuthenticated', 'publicKeyAddress']);
  assert.equal(literal(fields[1].value), false);
  // K's current consumer intentionally omits nowMs, so its default clock runs.
  const origins = [];
  for (const origin of exactlyOne(corpus.index.modules.filter((entry) => entry.sha256 === factorySha), 'predicate variant').origins) {
    const found = await corpus.factory(553301, { source: origin.source });
    assert.equal(found.provenance.sha256, factorySha);
    origins.push(found.provenance);
  }
  const receipt = { schemaVersion: 1, anchors: corpus.anchors, factory: factory.provenance, origins,
    sourceAdaptedPath: kernelPath, sourceAdaptedSha256: sha256(output), witnesses,
    consumer: { factory: consumer.provenance, import: consumer.witness(binding, 'predicate import'),
      call: consumer.witness(call, 'actual AuthProviders K call'), expression: consumer.text(call),
      limitation: 'Only K has an observed caller in this consumer; exported O and U are preserved without a reachability claim.' },
    decoderBoundary: '683023 is injected through its S export; its cross-chunk variant selection is unresolved. No default variant is chosen.',
    limitation: 'Unverified frontend state decisions only; no server session, JWT signature or backend authorization verification.' };
  const json = JSON.stringify(receipt, null, 2) + '\n';
  if (check) assert.deepEqual(JSON.parse(await readFile(path.join(appRoot, receiptPath), 'utf8')), receipt);
  else await writeFile(path.join(appRoot, receiptPath), json);
  return receipt;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert.ok(process.argv.slice(2).every((argument) => argument === '--write'));
  await recover({ check: !process.argv.includes('--write') });
  console.log('Original auth-state553301 and actual AuthProviders K caller verified.');
}
