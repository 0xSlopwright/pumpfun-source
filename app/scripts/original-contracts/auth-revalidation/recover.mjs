// Static source adaptation only; neither retained factory is evaluated.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from '@babel/parser';
import { generate } from '@babel/generator';
import { openCorpus, exactlyOne, findNodes, member, literal, sha256 } from '../source.mjs';

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const consumerSource = 'evidence/web/objects/9bafadffbe6dc98b.js';
const consumerSha = '4d12898c1c6cd0bc4e8518537175ecf57e5edf14a6723c4c15f8aad0bf97a400';
const requestSha = '23bc387a95434710efbfc32c36fada4e1d869debdd5b62b86e693ded868b0dbd';
const outputDir = 'packages/frontend/src/original-contracts/auth-revalidation';
const receiptPath = 'research/original-auth-revalidation-20261028/PROVENANCE.json';
const id = (name) => ({ type: 'Identifier', name });
const property = (name, value) => ({ type: 'ObjectProperty', key: id(name), value, shorthand: false, computed: false });
const variable = (name, init) => ({ type: 'VariableDeclaration', kind: 'const', declarations: [{ type: 'VariableDeclarator', id: id(name), init }] });
const block = (body) => ({ type: 'BlockStatement', body });
const returned = (argument) => ({ type: 'ReturnStatement', argument });
const fn = (name, params, body) => ({ type: 'FunctionDeclaration', id: id(name), params: params.map(id), body: block(body), generator: false, async: false });
const exported = (declaration) => ({ type: 'ExportNamedDeclaration', declaration, specifiers: [], source: null });
const code = (node) => generate(node, { comments: false }).code;

export function assertOriginalAdaptation(actual, expected) {
  const metadata = ['start', 'end', 'loc', 'extra', 'leadingComments', 'trailingComments', 'innerComments', 'comments'];
  const ast = (text) => JSON.parse(JSON.stringify(parse(text, { sourceType: 'module' }).program,
    (key, value) => metadata.includes(key) ? undefined : value));
  assert.deepEqual(ast(actual), ast(expected), 'auth revalidation differs from authenticated original AST');
  assert.equal(sha256(actual), sha256(expected), 'auth revalidation generated bytes changed');
}

async function originProof(corpus, factory) {
  const variant = exactlyOne(corpus.index.modules.filter((entry) => entry.sha256 === factory.provenance.sha256), 'selected variant');
  const origins = [];
  for (const origin of variant.origins) {
    const found = await corpus.factory(factory.id, { source: origin.source });
    assert.equal(found.provenance.sha256, variant.sha256);
    origins.push(found.provenance);
  }
  return origins;
}

export async function recover({ check = true } = {}) {
  const corpus = await openCorpus(appRoot);
  const request = await corpus.factory(174764, { source: consumerSource });
  assert.equal(request.provenance.sha256, requestSha);
  const [requestFunction, requestExports] = request.node.body.body;
  assert.equal(request.node.body.body.length, 2);
  assert.equal(requestFunction.type, 'FunctionDeclaration');
  assert.equal(requestFunction.async, true);
  assert.ok(member(requestExports.expression?.callee, request.runtime, 's'));
  const exports = requestExports.expression.arguments[0].elements;
  assert.equal(exports.length, 3);
  assert.equal(literal(exports[0]), 'f'); assert.equal(literal(exports[1]), 0);
  assert.equal(exports[2].name, requestFunction.id.name);
  const requestOutput = `// Original174764 ${requestSha}; request client remains injected.\n` +
    code(exported(requestFunction)) + '\n';

  const consumer = await corpus.factory(589428, { source: consumerSource });
  assert.equal(consumer.provenance.sha256, consumerSha);
  const requestImport = exactlyOne(findNodes(consumer.node, (node) => node.type === 'VariableDeclarator' &&
    member(node.init?.callee, consumer.runtime, 'i') && node.init.arguments[0]?.value === 174764), 'request import');
  assert.equal(requestImport.id.name, 'tj');
  const storageHelper = exactlyOne(findNodes(consumer.node, (node) => node.type === 'FunctionDeclaration' && node.id.name === 'tN'), 'storage helper');
  const cleanup = exactlyOne(findNodes(consumer.node, (node) => node !== consumer.node && node.type === 'ArrowFunctionExpression' &&
    findNodes(node, (child) => child.type === 'StringLiteral' && child.value === 'moderator-storage').length > 0), 'clear UI callback');
  const revalidate = exactlyOne(findNodes(consumer.node, (node) => node !== consumer.node && node.type === 'ArrowFunctionExpression' && node.async &&
    findNodes(node, (child) => child.type === 'StringLiteral' && child.value === 'rejected').length > 0), 'revalidate UI callback');
  const clearCall = exactlyOne(findNodes(cleanup, (node) => node.type === 'CallExpression' &&
    node.callee.type === 'SequenceExpression' && member(node.callee.expressions.at(-1), 'd', 'c')), 'clear cookie call');
  assert.equal(findNodes(cleanup, (node) => node.type === 'CallExpression' && node.callee.name === 'w' && literal(node.arguments[0]) === true).length, 1);
  const requestCall = exactlyOne(findNodes(revalidate, (node) => node.type === 'CallExpression' &&
    node.callee.type === 'SequenceExpression' && member(node.callee.expressions.at(-1), 'tj', 'f')), 'request consumer call');
  assert.ok(member(requestCall.arguments[0].callee.expressions.at(-1), 'eD', 'j'));
  const visible = exactlyOne(findNodes(consumer.node, (node) => node.type === 'VariableDeclarator' && node.id.name === 'I' &&
    node.init?.type === 'ConditionalExpression' && node.init.test.name === '_'), 'visible claims projection');
  const ready = exactlyOne(findNodes(consumer.node, (node) => node.type === 'VariableDeclarator' && node.id.name === 'B' &&
    node.init?.type === 'LogicalExpression' && node.init.right.name === '_'), 'authReady projection');
  const consumerOutput = `// Original589428 callbacks/projections ${consumerSha}.\n` +
    '// External cookie/storage/state/request operations remain explicit ports.\n' +
    code(exported(fn('createConsumerKernel', ['d', 'localStorage', 'w', 'eD', 'tj'], [
      storageHelper, variable('P', cleanup), variable('L', revalidate),
      returned({ type: 'ObjectExpression', properties: [property('clearUiState', id('P')), property('revalidateUiSession', id('L'))] }),
    ]))) + '\n' +
    code(exported(fn('visibleUnverifiedClaims', ['_', 'b'], [returned(visible.init)]))) + '\n' +
    code(exported(fn('capturedAuthReadyFlag', ['x', 'b', '_'], [returned(ready.init)]))) + '\n';
  const outputs = [['request.mjs', requestOutput], ['consumer.mjs', consumerOutput]];
  for (const [name, output] of outputs) {
    const destination = path.join(appRoot, outputDir, name);
    if (check) assertOriginalAdaptation(await readFile(destination, 'utf8'), output);
    else await writeFile(destination, output);
  }
  const receipt = { schemaVersion: 1, anchors: corpus.anchors,
    request: { factory: request.provenance, origins: await originProof(corpus, request),
      witnesses: [request.witness(requestFunction, 'request and verdict'), request.witness(requestExports, 'export f')] },
    consumer: { factory: consumer.provenance, origins: await originProof(corpus, consumer),
      witnesses: [[requestImport, 'request import174764'], [storageHelper, 'storage helper'], [cleanup, 'clear UI callback'],
        [revalidate, 'revalidate UI callback'], [clearCall, 'cookie clear operation'], [requestCall, 'actual request caller'],
        [visible, 'visible claims projection'], [ready, 'authReady projection']].map(([node, label]) => consumer.witness(node, label)) },
    outputs: outputs.map(([name, output]) => ({ path: `${outputDir}/${name}`, sha256: sha256(output) })),
    limitation: 'Client request→verdict→UI cleanup only; no original server implementation, authentication verification, network client or React provider is recovered.' };
  if (check) assert.deepEqual(JSON.parse(await readFile(path.join(appRoot, receiptPath), 'utf8')), receipt);
  else await writeFile(path.join(appRoot, receiptPath), JSON.stringify(receipt, null, 2) + '\n');
  return receipt;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert.ok(process.argv.slice(2).every((argument) => argument === '--write'));
  await recover({ check: !process.argv.includes('--write') });
  console.log('Original174764 request/verdict and589428 UI cleanup/projections verified.');
}
