import { parse } from "@babel/parser";
import { generate } from "@babel/generator";
import {
  openCorpus,
  exactlyOne,
  findNodes,
  member,
  literal,
  sha256,
} from "../source.mjs";
const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../..",
);
const source = "evidence/web/objects/9bafadffbe6dc98b.js";
const providerSha =
  "4d12898c1c6cd0bc4e8518537175ecf57e5edf14a6723c4c15f8aad0bf97a400";
const pendingSha =
  "b0d04ecd2aaa0755744a65c059b73905c135ffea314511d44102db5c99b79cdf";
const outDir = "packages/frontend/src/original-contracts/auth-display-restore";
const receiptPath =
  "research/original-auth-display-restore-20261028/PROVENANCE.json";
const id = (name) => ({ type: "Identifier", name });
const code = (node) => generate(node, { comments: false }).code;
const returned = (argument) => ({ type: "ReturnStatement", argument });
const fn = (name, params, body) => ({
  type: "ExportNamedDeclaration",
  declaration: {
    type: "FunctionDeclaration",
    id: id(name),
    params: params.map(id),
    body: { type: "BlockStatement", body },
    generator: false,
    async: false,
  },
  specifiers: [],
  source: null,
});
export function assertOriginalAdaptation(actual, expected) {
  const meta = [
    "start",
    "end",
    "loc",
    "extra",
    "leadingComments",
    "trailingComments",
    "innerComments",
    "comments",
  ];
  const ast = (text) =>
    JSON.parse(
      JSON.stringify(
        parse(text, { sourceType: "module" }).program,
        (key, value) => (meta.includes(key) ? undefined : value),
      ),
    );
  assert.deepEqual(
    ast(actual),
    ast(expected),
    "display restore differs from authenticated original AST",
  );
  assert.equal(
    sha256(actual),
    sha256(expected),
    "display restore generated bytes changed",
  );
}
async function allOrigins(corpus, factory) {
  const variant = exactlyOne(
    corpus.index.modules.filter((m) => m.sha256 === factory.provenance.sha256),
    "variant",
  );
  const origins = [];
  for (const origin of variant.origins) {
    const f = await corpus.factory(factory.id, { source: origin.source });
    assert.equal(f.provenance.sha256, variant.sha256);
    origins.push(f.provenance);
  }
  return origins;
}
export async function recover({ check = true } = {}) {
  const corpus = await openCorpus(root);
  const provider = await corpus.factory(589428, { source });
  assert.equal(provider.provenance.sha256, providerSha);
  const pending = await corpus.factory(594435, { source });
  assert.equal(pending.provenance.sha256, pendingSha);
  const pendingBody = [...pending.node.body.body];
  const registration = pendingBody.pop();
  assert.ok(member(registration.expression?.callee, pending.runtime, "s"));
  const entries = registration.expression.arguments[0].elements;
  assert.equal(entries.length, 9);
  const properties = [];
  for (const [index, name] of [
    [0, "P"],
    [3, "g"],
    [6, "c"],
  ]) {
    assert.equal(literal(entries[index]), name);
    assert.equal(literal(entries[index + 1]), 0);
    properties.push({
      type: "ObjectProperty",
      key: id(name),
      value: entries[index + 2],
      computed: false,
      shorthand: false,
    });
  }
  pendingBody.push(returned({ type: "ObjectExpression", properties }));
  const pendingOutput =
    `// Original594435 ${pendingSha}; storage is explicitly injected.\n` +
    code(fn("createPendingLogoutKernel", ["localStorage"], pendingBody)) +
    "\n";
  const restore = exactlyOne(
    findNodes(
      provider.node,
      (n) => n.type === "FunctionDeclaration" && n.id?.name === "te",
    ),
    "restore function",
  );
  const state = exactlyOne(
    findNodes(
      provider.node,
      (n) =>
        n.type === "VariableDeclaration" &&
        n.declarations.some((d) => d.id.name === "e7"),
    ),
    "once/key declaration",
  );
  assert.deepEqual(
    state.declarations.map((n) => n.id.name),
    ["e9", "e7"],
  );
  const effect = exactlyOne(
    findNodes(
      provider.node,
      (n) => n.type === "FunctionDeclaration" && n.id?.name === "tt",
    ),
    "effect consumer",
  );
  const call = exactlyOne(
    findNodes(
      effect,
      (n) => n.type === "CallExpression" && n.callee.name === "te",
    ),
    "actual restore call",
  );
  assert.equal(call.arguments[0].properties[0].key.name, "clientServerUrl");
  const effectCall = exactlyOne(
    findNodes(
      effect,
      (n) =>
        n.type === "CallExpression" &&
        n.callee.type === "SequenceExpression" &&
        member(n.callee.expressions.at(-1), "o", "useEffect"),
    ),
    "actual effect",
  );
  const imports = [30181, 683023, 594435].map((moduleId) =>
    exactlyOne(
      findNodes(
        provider.node,
        (n) =>
          n.type === "VariableDeclarator" &&
          member(n.init?.callee, provider.runtime, "i") &&
          n.init.arguments[0]?.value === moduleId,
      ),
      `import${moduleId}`,
    ),
  );
  const pendingMarker = exactlyOne(
    findNodes(
      provider.node,
      (node) =>
        node.type === "CallExpression" &&
        node.callee.type === "SequenceExpression" &&
        member(node.callee.expressions.at(-1), "e8", "c"),
    ),
    "actual logout pending marker",
  );
  const restoreOutput =
    `// Original589428 display-restore function ${providerSha}; capabilities are injected.\n` +
    code(
      fn(
        "createDisplayRestoreKernel",
        [
          "d",
          "e8",
          "e5",
          "e6",
          "localStorage",
          "AbortController",
          "setTimeout",
          "clearTimeout",
          "a",
        ],
        [state, restore, returned(id("te"))],
      ),
    ) +
    "\n";
  const outputs = [
    ["pending.mjs", pendingOutput],
    ["restore.mjs", restoreOutput],
  ];
  for (const [name, output] of outputs) {
    const file = path.join(root, outDir, name);
    if (check) assertOriginalAdaptation(await readFile(file, "utf8"), output);
    else await writeFile(file, output);
  }
  const receipt = {
    schemaVersion: 1,
    anchors: corpus.anchors,
    pending: {
      factory: pending.provenance,
      origins: await allOrigins(corpus, pending),
      witnesses: pending.node.body.body.map((n) =>
        pending.witness(n, "original pending state/export"),
      ),
    },
    provider: {
      factory: provider.provenance,
      origins: await allOrigins(corpus, provider),
      witnesses: [
        [state, "once guard/key"],
        [restore, "display restore"],
        [effect, "actual effect consumer"],
        [call, "restore call"],
        [effectCall, "effect subscription"],
        [pendingMarker, "actual logout pending marker"],
        ...imports.map((n) => [n, "dependency import"]),
      ].map(([node, label]) => provider.witness(node, label)),
    },
    outputs: outputs.map(([name, output]) => ({
      path: `${outDir}/${name}`,
      sha256: sha256(output),
    })),
    limitation:
      "Unverified display-state recovery only; no original transport, server auth, browser credential access or complete React provider is supplied.",
  };
  if (check)
    assert.deepEqual(
      JSON.parse(await readFile(path.join(root, receiptPath), "utf8")),
      receipt,
    );
  else
    await writeFile(
      path.join(root, receiptPath),
      JSON.stringify(receipt, null, 2) + "\n",
    );
  return receipt;
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  assert.ok(process.argv.slice(2).every((arg) => arg === "--write"));
  await recover({ check: !process.argv.includes("--write") });
  console.log(
    "Original display restore, pending logout and effect caller verified.",
  );
}
